// does any of the mic's guesses say this word?
export function heardWord(alternatives: string[], kana: string): boolean {
  const targets = [kana, ...(WRITTEN[kana] ?? [])].map(normJa);
  return alternatives.some((a) => {
    const n = normJa(a);
    return n.length > 0 && targets.some((t) => n === t || (n.includes(t) && n.length <= t.length + 3));
  });
}

// the first guess, cleaned up, for "I heard: ..."
export function heardText(alternatives: string[]): string {
  return (alternatives[0] ?? "").replace(/\s+/g, " ").trim();
}
