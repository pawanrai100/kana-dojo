import { toHiragana } from "@/lib/kana/hiragana";

// the mic hands back whatever japanese the browser thinks you said,
// often in kanji (say ねこ and you get 猫). so every speaking word also
// lists how it's usually written, and we compare after flattening both

export function normJa(s: string): string {
  return toHiragana(
    s
      .normalize("NFKC")
      .toLowerCase()
      .replace(/[\s、。，．,.!！?？「」『』"'～~・…]/g, ""),
  );
}

