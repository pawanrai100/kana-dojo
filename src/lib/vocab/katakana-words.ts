function build(): VocabWord[] {
  const out: VocabWord[] = [];
  const seen = new Set<string>();
  for (const [category, list] of Object.entries(RAW) as [VocabCategory, [string, string][]][]) {
    for (const [kana, meaning] of list) {
      const units = splitKana(kana);
      // catch typos when the site builds, not when someone plays
      if (!units.every((k) => isKnownKana(k) && scriptOf(k) === "katakana")) throw new Error(`bad katakana word: ${kana}`);
      if (seen.has(kana)) throw new Error(`duplicate katakana word: ${kana}`);
      seen.add(kana);
      out.push({ id: kana, kana, romaji: toRomaji(kana), meaning, category });
    }
  }
  return out;
}

export const KATAKANA_VOCAB: VocabWord[] = build();
